"""Train the DGA model: does a domain name look machine-generated?

Malware that uses a domain generation algorithm (DGA) makes up hundreds of names a day
("qgcyquqgygcsaausi.com") and tries them until one answers. Seeing a device look up
many such names is a strong sign of infection.

Data: ExtraHop's DGA Detection Training Dataset (MIT licence, github.com/ExtraHop/
DGA-Detection-Training-Dataset): 16.2 million names without their ending, about half
generated by known DGA families and half benign. The model is the same kind as the link
model (character pieces + logistic regression, detectors/url/model.py), on the name only.

    python detectors/net/train_dga.py --data dga-training-data-encoded.json.gz
"""
import argparse
import gzip
import json
import os
import random
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

from detectors.url.train_url import fit, rates          # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
MODEL = os.path.join(HERE, "dga_model.npz")


def load(path, per_class=400_000, seed=42):
    """A random sample of each class (reservoir sampling, one pass over 16 million lines)."""
    rng = random.Random(seed)
    keep = {"dga": [], "benign": []}
    seen = {"dga": 0, "benign": 0}
    with gzip.open(path, "rt", encoding="utf-8") as f:
        for line in f:
            if not line.startswith("{"):
                continue
            row = json.loads(line)
            name, label = row.get("domain", "").strip().lower(), row.get("threat")
            if label not in keep or not name:
                continue
            seen[label] += 1
            bucket = keep[label]
            if len(bucket) < per_class:
                bucket.append(name)
            else:
                j = rng.randrange(seen[label])
                if j < per_class:
                    bucket[j] = name
    print(f"read {seen['dga']:,} DGA and {seen['benign']:,} benign names; sampled {per_class:,} of each")
    return keep


def train(path, out=MODEL, per_class=400_000, seed=42):
    import pandas as pd
    from sklearn.model_selection import train_test_split
    t0 = time.time()
    data = load(path, per_class, seed)
    df = pd.DataFrame([(n, 1) for n in data["dga"]] + [(n, 0) for n in data["benign"]], columns=["domain", "phishing"])
    df = df.drop_duplicates("domain")
    df = df[df.groupby("domain")["phishing"].transform("nunique") == 1]
    df["suffix"] = ""
    tr, te = train_test_split(df, test_size=0.2, random_state=seed, stratify=df["phishing"])
    model, _ = fit(tr)
    p = model.scores(list(zip(te["domain"], te["suffix"])))
    rates(te["phishing"].values, p, "Held-out ExtraHop names (none seen in training)", thresholds=(0.5, 0.8, 0.9))
    model.meta = {"version": 1, "trained_on": "ExtraHop DGA Detection Training Dataset (MIT)",
                  "train_names": int(len(tr)), "test_names": int(len(te)), "date": time.strftime("%Y-%m-%d")}
    model.save(out)
    print(f"Saved the DGA model -> {out} ({os.path.getsize(out) / 1e6:.1f} MB, {time.time() - t0:.0f} s)")
    return model


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--data", required=True, help="dga-training-data-encoded.json.gz")
    ap.add_argument("--out", default=MODEL)
    ap.add_argument("--per-class", type=int, default=400_000)
    a = ap.parse_args()
    train(a.data, a.out, a.per_class)


if __name__ == "__main__":
    main()
